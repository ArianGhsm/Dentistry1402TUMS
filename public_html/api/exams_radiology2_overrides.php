function dent_exams_apply_radiology2_overrides(array $bank): array
{
    $overrides = dent_exams_radiology2_overrides();
    $exams = &$bank['catalogs']['shared']['courses']['radiology2']['exams'];

    if (is_array($exams)) {
        foreach ($exams as &$exam) {
            if (!is_array($exam)) {
                continue;
            }

            $slug = trim((string) ($exam['slug'] ?? ''));
            if ($slug === '' || !isset($overrides[$slug]) || !is_array($overrides[$slug])) {
                continue;
            }

            foreach ($overrides[$slug] as $key => $value) {
                $exam[$key] = $value;
            }
        }
        unset($exam);
    }

    return dent_exams_sync_question_counts($bank);
}

function dent_exams_sync_question_counts(array $bank): array
{
    $catalogs = $bank['catalogs'] ?? null;
    if (!is_array($catalogs)) {
        return $bank;
    }

    foreach ($catalogs as &$catalog) {
        $courses = &$catalog['courses'];
        if (!is_array($courses)) {
            continue;
        }

        foreach ($courses as &$course) {
            $exams = &$course['exams'];
            if (!is_array($exams)) {
                continue;
            }

            foreach ($exams as &$exam) {
                if (!is_array($exam)) {
                    continue;
                }

                $questions = $exam['questions'] ?? null;
                if (!is_array($questions)) {
                    continue;
                }

                $exam['questionCount'] = count($questions);
            }
            unset($exam);
        }
        unset($course);
    }
    unset($catalog);

    return $bank;
}

